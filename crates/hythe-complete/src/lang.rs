//! Languages and the static completion data tuned for each.

use std::path::Path;

use crate::Kind;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Language {
    Rust,
    Python,
    JavaScript,
    TypeScript,
    Go,
    C,
    Cpp,
    Java,
    /// Anything else: completes from words in the open files only.
    Plain,
}

impl Language {
    pub fn from_extension(ext: &str) -> Language {
        match ext.to_ascii_lowercase().as_str() {
            "rs" => Language::Rust,
            "py" | "pyw" | "pyi" => Language::Python,
            "js" | "jsx" | "mjs" | "cjs" => Language::JavaScript,
            "ts" | "tsx" | "mts" | "cts" => Language::TypeScript,
            "go" => Language::Go,
            "c" | "h" => Language::C,
            "cc" | "cpp" | "cxx" | "hpp" | "hh" | "hxx" => Language::Cpp,
            "java" => Language::Java,
            _ => Language::Plain,
        }
    }

    pub fn from_path(path: &Path) -> Language {
        path.extension()
            .and_then(|e| e.to_str())
            .map(Language::from_extension)
            .unwrap_or(Language::Plain)
    }

    pub fn name(self) -> &'static str {
        match self {
            Language::Rust => "Rust",
            Language::Python => "Python",
            Language::JavaScript => "JavaScript",
            Language::TypeScript => "TypeScript",
            Language::Go => "Go",
            Language::C => "C",
            Language::Cpp => "C++",
            Language::Java => "Java",
            Language::Plain => "Plain Text",
        }
    }

    pub(crate) fn data(self) -> &'static LangData {
        match self {
            Language::Rust => &RUST,
            Language::Python => &PYTHON,
            Language::JavaScript => &JAVASCRIPT,
            Language::TypeScript => &TYPESCRIPT,
            Language::Go => &GO,
            Language::C => &C,
            Language::Cpp => &CPP,
            Language::Java => &JAVA,
            Language::Plain => &PLAIN,
        }
    }
}

/// `(label, text to insert or "" for the label, short description)`.
pub(crate) type Entry = (&'static str, &'static str, &'static str);
/// `(trigger, description, body)`. `$0` marks where the cursor ends up.
pub(crate) type Snippet = (&'static str, &'static str, &'static str);

pub(crate) struct LangData {
    pub keywords: &'static [&'static str],
    /// Standard-library names usable on their own: types, macros, functions.
    pub builtins: &'static [Entry],
    /// Names that commonly follow a `.` (or `::`).
    pub members: &'static [Entry],
    pub snippets: &'static [Snippet],
    /// Preceding keyword -> kind of the identifier that follows it.
    pub defs: &'static [(&'static str, Kind)],
    pub line_comment: &'static str,
    pub block_comments: bool,
    /// `'a` is a lifetime, not a string.
    pub lifetimes: bool,
    pub triple_quotes: bool,
    pub backtick_strings: bool,
    /// `#include`, `#define` and friends.
    pub preprocessor: bool,
    /// `::` introduces members (Rust, C++).
    pub scope_operator: bool,
    /// Identifiers may contain `$` (JavaScript, TypeScript, Java).
    pub dollar_idents: bool,
}

const NONE: &[Entry] = &[];

